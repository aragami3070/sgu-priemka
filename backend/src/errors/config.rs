use thiserror::Error;

/// Ошибки загрузки и проверки конфигурации приложения.
#[derive(Debug, Error)]
pub(crate) enum ConfigError {
    /// Файл `.env` существует, но не может быть прочитан или разобран.
    #[error("не удалось загрузить .env: {0}")]
    Dotenv(String),
    /// Обязательная переменная окружения отсутствует или пуста.
    #[error("обязательная переменная окружения {0} отсутствует или пуста")]
    Missing(&'static str),
    /// Значение переменной окружения не соответствует ожидаемому формату.
    #[error("некорректное значение {name} `{value}`; ожидается {expected}")]
    InvalidValue {
        /// Имя переменной окружения.
        name: &'static str,
        /// Полученное значение.
        value: String,
        /// Описание ожидаемого формата.
        expected: &'static str,
    },
}
