use std::path::PathBuf;

use thiserror::Error;

/// Ошибка чтения или проверки файла соответствий учебных групп.
#[derive(Debug, Error)]
pub(crate) enum GroupServiceError {
    /// Файл групп не удалось прочитать.
    #[error("не удалось прочитать файл групп `{path}`: {source}")]
    Read {
        /// Путь к TOML-файлу групп.
        path: PathBuf,
        /// Исходная ошибка файловой системы.
        #[source]
        source: std::io::Error,
    },
    /// TOML-файл групп имеет некорректный синтаксис.
    #[error("не удалось разобрать TOML-файл групп: {0}")]
    Parse(#[from] toml::de::Error),
    /// Ключ группы не является положительным числом.
    #[error("некорректный номер группы `{0}` в TOML-файле")]
    InvalidNumber(String),
    /// Название группы пустое.
    #[error("пустое название группы для номера {0}")]
    EmptyName(usize),
    /// Корневое значение TOML не является таблицей.
    #[error("корневое значение TOML-файла групп должно быть таблицей")]
    InvalidRoot,
    /// Файл групп не содержит корректный UTF-8.
    #[error("файл групп должен быть в кодировке UTF-8")]
    InvalidUtf8,
}
